/// L'ISTANTE DELLE PROVE. Ordine U voce 00.
///
/// **Il fatto che ha reso necessario questo file.** Tre prove di
/// `la_festa_arriva_sempre_test.dart` passavano il 14 agosto 2026 e fallivano il
/// 15, senza che una riga di codice fosse cambiata. **Una suite che cambia
/// colore col giorno non e' una suite: e' un oroscopo**, e la sua parola verde
/// smette di valere per tutti.
///
/// Misurato, e non dedotto: una `gettata` sola accende il traguardo `cal_6`
/// **solo quando il cielo del giorno porta la luna nuova**. Il 13 e il 14 agosto
/// quella finestra e' aperta, il 15 e il 16 e' chiusa, e con lei se ne va
/// l'unico traguardo che quelle prove potevano accendere.
///
/// **Perche' proprio questo istante.** Non e' il giorno che fa passare le prove:
/// e' un giorno in cui c'e' qualcosa da vedere. Una prova che sorveglia la festa
/// ha bisogno che un traguardo si accenda, e sceglierne uno in cui non si accende
/// niente vorrebbe dire sorvegliare il nulla. Il giorno si dichiara qui, in un
/// punto solo, cosi' chi lo cambia vede subito quante prove tocca.
library;

/// **IL GIORNO DELLE PROVE**, mezzogiorno, con la finestra della luna nuova
/// aperta: 14 agosto 2026.
final DateTime istanteDelleProve = DateTime(2026, 8, 14, 12);

/// L'orologio da passare a chi lo chiede.
DateTime orologioDelleProve() => istanteDelleProve;
