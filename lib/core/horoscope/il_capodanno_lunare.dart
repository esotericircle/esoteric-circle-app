  /// Il giorno del Capodanno lunare dell'anno [anno], o null fuori tabella.
  static DateTime? di(int anno) {
    if (anno < primoAnno || anno > ultimoAnno) return null;
    final v = date[anno - primoAnno];
    return DateTime(anno, v ~/ 100, v % 100);
  }

  /// L'anno cinese in cui cade la data civile [giorno]: quello del
  /// calendario, o il precedente se [giorno] viene prima del Capodanno.
  /// Null fuori dalla tabella.
  static int? annoCinese(DateTime giorno) {
    final capodanno = di(giorno.year);
    if (capodanno == null) return null;
    final d = DateTime(giorno.year, giorno.month, giorno.day);
    final anno = d.isBefore(capodanno) ? giorno.year - 1 : giorno.year;
    return anno < primoAnno ? null : anno;
  }
}
