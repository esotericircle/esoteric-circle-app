  CondizioneDelTraguardo condizione,
  String frase,
  int posizione,
) =>
    Traguardo(
      id: id,
      nome: nome,
      famiglia: famiglia,
      condizione: condizione,
      frase: frase,
      posizione: posizione,
      eGrande: true,
    );

