/// IL FIORE DI LOTO, il sentiero di Aura.
///
/// I Petali del Risveglio sono i cinquanta traguardi piccoli, le Fioriture
/// sono i cinque grandi. Il tono e' quello di Aura: il respiro, il corpo che
/// sa prima della testa, la cura senza promesse.
///
/// I GESTI DI QUESTO SENTIERO: `soffio` (il Soffio del Destino),
/// `meditazione`, `chakra`, `viso` (la Costellazione del Viso), `archetipo`,
/// `consulto_aura`. Piu' i gesti comuni: `alba`, `oracolo`, `tramonto`.
Traguardo _t(
  String id,
  String nome,
  FamigliaDelTraguardo famiglia,
  CondizioneDelTraguardo condizione,
  String frase,
  int posizione,
) =>
    Traguardo(
      id: id,
      nome: nome,
      famiglia: famiglia,
      condizione: condizione,
      frase: frase,
      posizione: posizione,
    );

/// Lo stesso, per i cinque GRANDI: il dato dice che sono grandi, cosi' la
/// posizione non deve indovinarlo.
