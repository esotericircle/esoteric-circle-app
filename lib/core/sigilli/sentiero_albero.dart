/// L'ALBERO DELLA VITA, il sentiero di Caligo.
///
/// I Frutti dell'Albero sono i cinquanta traguardi piccoli, le Sefirot
/// Maggiori sono i cinque grandi. Il tono e' quello di Caligo: la pietra, la
/// notte, il presagio che non consola e non minaccia.
///
/// I GESTI DI QUESTO SENTIERO: `gettata` (una gettata di rune), `tramonto`
/// (la Runa del Tramonto), `sogno` (il Rito del Sogno), `sigillo` (il sigillo
/// magico disegnato), `animale` (l'Animale Guida), `consulto_caligo`.
Traguardo _t(
  String id,
  String nome,
  FamigliaDelTraguardo famiglia,
  CondizioneDelTraguardo condizione,
  String frase,
  int posizione,
) =>
    Traguardo(
      id: id,
      nome: nome,
      famiglia: famiglia,
      condizione: condizione,
      frase: frase,
      posizione: posizione,
    );

/// Lo stesso, per i cinque GRANDI: il dato dice che sono grandi, cosi' la
/// posizione non deve indovinarlo.
Traguardo _g(
  String id,
  String nome,
  FamigliaDelTraguardo famiglia,
  CondizioneDelTraguardo condizione,
  String frase,
  int posizione,
) =>
    Traguardo(
      id: id,
      nome: nome,
      famiglia: famiglia,
      condizione: condizione,
      frase: frase,
      posizione: posizione,
      eGrande: true,
    );

